"""Build the hosted model detector from the firmware's MultiPlus-II catalogue."""

import argparse
import json
from pathlib import Path
import re


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "firmware" / "vebus_listener" / "src" / "multiplus_ii.h"
OUTPUT = ROOT / "website" / "public" / "compatibility" / "models.js"


def catalogue():
    source = SOURCE.read_text(encoding="utf-8")
    match = re.search(r"static constexpr Model models\[\] = \{([\s\S]*?)\n\s*\};", source)
    if match is None:
        raise ValueError("The MultiPlus-II catalogue has an unexpected layout.")
    rows = re.findall(r'\{0x([0-9]{4}),\s*(12|24|48),\s*"([^"\r\n]+)"\}', match[1])
    if not rows or match[1].count("{0x") != len(rows):
        raise ValueError("A MultiPlus-II catalogue entry could not be parsed.")
    models = {}
    for product, voltage, name in rows:
        # Product IDs are BCD: 0x2623 is decimal firmware prefix 2623.
        prefix = int(product)
        if not 2600 <= prefix <= 2699 or prefix in models:
            raise ValueError("The MultiPlus-II catalogue contains an invalid or duplicate prefix.")
        models[prefix] = {"voltage": int(voltage), "name": name}
    return models


def generated_models():
    rows = ",\n".join(f"  [{prefix}, {json.dumps(model, ensure_ascii=False)}]"
                       for prefix, model in catalogue().items())
    return """// Generated by tools/build_hosted_models.py. Do not edit.
// Firmware prefixes identify the inverter family; enclosure variants can share a prefix.
const MODELS = new Map([
""" + rows + """
]);

export function detectModel(profile) {
  const firmware = profile?.schema_firmware;
  if (!Number.isInteger(firmware) || firmware < 1000000 || firmware > 9999999) {
    throw new Error('The inverter model could not be detected from this backup.');
  }
  const model = MODELS.get(Math.floor(firmware / 1000));
  if (!model || profile.nominal_voltage !== model.voltage) {
    throw new Error('The inverter model and battery voltage could not be verified.');
  }
  return model.name;
}
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if the hosted model catalogue is stale")
    args = parser.parse_args()
    expected = generated_models()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != expected:
            parser.error("The hosted model catalogue is stale. Run python tools/build_hosted_models.py.")
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(expected, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
