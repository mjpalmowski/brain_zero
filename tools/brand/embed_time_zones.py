"""Embed IANA civil time for the controller from the Python tzdata package."""

import argparse
from datetime import datetime, timezone
from importlib import resources
from io import BytesIO
import json
from pathlib import Path
from struct import unpack_from
from zoneinfo import ZoneInfo

import tzdata


OUTPUT = (Path(__file__).resolve().parents[2] / "firmware" / "vebus_listener"
          / "src" / "controller_time_data.h")
FIRST_UTC = 1735689600  # 2025-01-01 00:00:00 UTC
LAST_UTC = 2147483647   # 2038-01-19 03:14:07 UTC
PROBE_INTERVAL = 6 * 3600


def explicit_transitions(tzif):
    """Read the 64-bit transition timestamps from a version 2+ TZif file."""
    if tzif[:5] not in (b"TZif2", b"TZif3", b"TZif4"):
        raise ValueError("Expected a version 2 or newer TZif file")
    utc, standard, leaps, times, types, chars = unpack_from(">6I", tzif, 20)
    second_header = 44 + 5 * times + 6 * types + chars + 8 * leaps + standard + utc
    if tzif[second_header:second_header + 5] != tzif[:5]:
        raise ValueError("Missing the second TZif header")
    count, = unpack_from(">I", tzif, second_header + 32)
    return unpack_from(f">{count}q", tzif, second_header + 44)


def rule_for(tzif, samples):
    zone = ZoneInfo.from_file(BytesIO(tzif))

    def offset_at(utc):
        local = datetime.fromtimestamp(utc, timezone.utc).astimezone(zone)
        seconds = int(local.utcoffset().total_seconds())
        minutes, remainder = divmod(seconds, 60)
        if remainder or not -1440 < minutes < 1440:
            raise ValueError(f"Unsupported UTC offset {seconds} seconds")
        return minutes, bool(local.dst())

    # Include each explicit transition, even if two fall within one probe
    # interval. After those, the TZif footer describes the recurring seasonal
    # transitions, which are spaced farther apart than the six-hour probes.
    points = samples.union(utc for utc in explicit_transitions(tzif)
                           if FIRST_UTC < utc <= LAST_UTC)
    initial = offset_at(FIRST_UTC)
    previous_utc, previous_offset = FIRST_UTC, initial
    changes = []
    for utc in sorted(points):
        offset = offset_at(utc)
        if offset != previous_offset:
            lo, hi = previous_utc, utc
            while hi - lo > 1:
                mid = (lo + hi) // 2
                if offset_at(mid) == previous_offset:
                    lo = mid
                else:
                    hi = mid
            changes.append((hi, *offset))
        previous_utc, previous_offset = utc, offset
    return initial, tuple(changes)


def generate():
    zoneinfo = resources.files("tzdata.zoneinfo")
    names = sorted(resources.files("tzdata").joinpath("zones").read_text(encoding="utf-8").splitlines())
    samples = set(range(FIRST_UTC + PROBE_INTERVAL, LAST_UTC, PROBE_INTERVAL))
    samples.add(LAST_UTC)
    by_tzif, by_rule = {}, {}
    zones, rules, changes = [], [], []
    for name in names:
        tzif = zoneinfo.joinpath(*name.split("/")).read_bytes()
        if tzif not in by_tzif:
            by_tzif[tzif] = rule_for(tzif, samples)
        initial, transitions = by_tzif[tzif]
        key = initial, transitions
        if key not in by_rule:
            by_rule[key] = len(rules)
            rules.append((len(changes), len(transitions), *initial))
            changes.extend(transitions)
        zones.append((name, by_rule[key]))
    if max(len(rules), len(changes)) >= 65536:
        raise ValueError("Too much time zone data for uint16_t indices")
    lines = [
        "// Generated by tools/brand/embed_time_zones.py. Do not edit.",
        f"// Source: IANA tzdb {tzdata.IANA_VERSION}, Python tzdata {tzdata.__version__}.",
        "// IANA time zone data is public domain: https://www.iana.org/time-zones",
        f"constexpr uint32_t FIRST_UTC = {FIRST_UTC}u;",
        f"constexpr uint32_t LAST_UTC = {LAST_UTC}u;",
        "",
        "constexpr Transition transitions[] = {",
        *(f"    {{{utc}u, {{{minutes}, {int(dst)}}}}}," for utc, minutes, dst in changes),
        "};",
        "",
        "constexpr Rule rules[] = {",
        *(f"    {{{start}, {count}, {{{minutes}, {int(dst)}}}}}," for start, count, minutes, dst in rules),
        "};",
        "",
        "constexpr Zone zones[] = {",
        *(f'    {{"{name}", {rule}}},' for name, rule in zones),
        "};",
        "",
        'constexpr char zone_names_json[] = R"json(' + json.dumps(names, separators=(",", ":")) + ')json";',
        "",
    ]
    print(f"IANA {tzdata.IANA_VERSION}: {len(zones)} names, {len(rules)} distinct rules, "
          f"{len(changes)} transitions")
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify the checked-in table")
    args = parser.parse_args()
    generated = generate()
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != generated:
            raise SystemExit(f"{OUTPUT} is out of date")
    else:
        OUTPUT.write_text(generated, encoding="utf-8", newline="\n")
