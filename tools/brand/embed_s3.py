def build() -> None:
    parts = ["// Generated by tools/brand/embed_s3.py from assets/brand/*.svg and shared styles.\n",
             "#pragma once\n#include <pgmspace.h>\n"]
    for symbol, filename in (("BRAND_LOGO", "brain-zero.svg"),
                             ("BRAND_LOGO_DARK", "brain-zero-dark.svg"),
                             ("BRAND_ICON", "brain-zero-icon.svg")):
        svg = (BRAND / filename).read_text(encoding="utf-8")
        assert ')BRAND"' not in svg
        parts.append(f'static const char {symbol}[] PROGMEM = R"BRAND({svg})BRAND";\n')
    parts.append(f'static const char BRAND_CSS[] PROGMEM = R"BRAND({CSS})BRAND";\n')
    OUTPUT.write_text("".join(parts), encoding="utf-8", newline="\n")
    print(f"Embedded three SVGs and local styles in {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    build()
