"""Embed complete, offline console translations in program flash."""
import argparse
import json
import re
from collections import Counter
from html import escape
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ASSETS = ROOT / "assets/brand"
OUTPUT = ROOT / "firmware/vebus_listener/src/language_assets.h"


def read_json(name):
    return json.loads((ASSETS / name).read_text(encoding="utf-8"))


def compact(value):
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"))


def placeholders(text):
    return Counter(re.findall(r"\{\w+\}", text))


def build():
    languages = read_json("venus-language-terms.json")["languages"]
    catalogue = read_json("ui-translations.json")
    keys = catalogue["english"]
    translations = catalogue["translations"]
    patterns = read_json("ui-message-patterns.json")
    if keys != sorted(set(keys)):
        raise ValueError("English console messages must be sorted and unique")
    if set(translations) != set(languages) - {"en"}:
        raise ValueError("Console catalogs must cover every offered language")
    if not set(patterns) <= set(keys):
        raise ValueError("A backend message pattern is missing from the console catalogs")

    parts = [
        "// Generated by tools/brand/embed_languages.py. This code is based on Victron Energy code.\n"
        "// See assets/brand/VENUS-TRANSLATIONS-LICENSE.txt.\n"
        "#pragma once\n#include <pgmspace.h>\n#include <string.h>\n",
    ]
    options, rows = [], []
    for code, item in languages.items():
        lang = code.replace("_", "-")
        localized = translations.get(code, {})
        if code != "en":
            if set(localized) != set(keys):
                raise ValueError(f"Incomplete console catalog for {lang}")
            for key in keys:
                if not localized[key].strip() or placeholders(localized[key]) != placeholders(key):
                    raise ValueError(f"Invalid {lang} translation for {key!r}")
        # The common English keys are sent once with the localizer. Each language
        # only needs its translations, in the same order, stored in program flash.
        messages = [localized[key] for key in keys] if code != "en" else []
        script = "window.bzLocale=" + compact({"lang": lang, "messages": messages}) + ";"
        assert ')LANG"' not in script
        parts.append(f'static const char UI_LANGUAGE_{code}[] PROGMEM = R"LANG({script})LANG";\n')
        rows.append(f'    {{"{code}", UI_LANGUAGE_{code}}},\n')
        options.append(f'<option value="{code}" lang="{lang}">{escape(item["name"])}</option>')
    parts.append("struct UiLanguage { const char *code; const char *script; };\n")
    parts.append("static const UiLanguage UI_LANGUAGES[] = {\n" + "".join(rows) + "};\n")
    parts.append("inline const UiLanguage *ui_language(const char *code) {\n"
                 "    for (const auto &item : UI_LANGUAGES) if (!strcmp(item.code, code)) return &item;\n"
                 "    return nullptr;\n}\n")
    parts.append('#define BRAIN_ZERO_LANGUAGE_OPTIONS R"LANG(' + "".join(options) + ')LANG"\n')
    localizer = (ASSETS / "ui-localize.js").read_text(encoding="utf-8")
    localizer = localizer.replace("/*BRAIN_ZERO_MESSAGE_KEYS*/[]", compact(keys))
    localizer = localizer.replace("/*BRAIN_ZERO_BACKEND_PATTERNS*/[]", compact(patterns))
    assert ')LANG"' not in localizer
    parts.append('static const char UI_TRANSLATE_JS[] PROGMEM = R"LANG(' + localizer + ')LANG";\n')
    return "".join(parts), len(languages), len(keys)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify that the generated header is current.")
    args = parser.parse_args()
    content, languages, keys = build()
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != content:
            raise SystemExit("Regenerate language_assets.h with tools/brand/embed_languages.py")
    else:
        OUTPUT.write_text(content, encoding="utf-8", newline="\n")
    print(f"Verified {keys} console messages across {languages} languages")
