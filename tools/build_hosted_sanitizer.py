"""Build the hosted parser from the independently tested offline sanitizer."""

import argparse
from pathlib import Path
import re


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "tools" / "rvsc-sanitizer.html"
OUTPUT = ROOT / "website" / "public" / "compatibility" / "sanitizer.js"


def generated_parser():
    source = SOURCE.read_text(encoding="utf-8")
    script = re.search(r'<script type="module" id="sanitizer-script">([\s\S]*?)</script>', source)[1]
    parser, separator, _ = script.partition('\nif (typeof document !== "undefined") {')
    if not separator or "export async function sanitizeRvsc(input)" not in parser:
        raise ValueError("The standalone sanitizer has an unexpected module layout.")
    return "// Generated by tools/build_hosted_sanitizer.py. Do not edit.\n" + parser.lstrip("\n") + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if the committed hosted parser is stale")
    args = parser.parse_args()
    expected = generated_parser()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != expected:
            parser.error("The hosted parser is stale. Run python tools/build_hosted_sanitizer.py.")
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(expected, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
